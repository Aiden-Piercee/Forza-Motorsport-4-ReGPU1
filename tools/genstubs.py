"""Write src/kernel/stubs.cpp: a weak fallback for every import the recompiled
code calls. Real implementations elsewhere in src/ override these.

  py -3 tools/genstubs.py <ppc_recomp_shared.h>... src/kernel/stubs.cpp

With several images (default.xex and the facade modules), pass every image's
ppc_recomp_shared.h: their imports share one implementation.
"""
import re
import sys

names = set()
for header in sys.argv[1:-1]:
    names |= set(re.findall(r"PPC_EXTERN_FUNC\(__imp__([A-Za-z_]\w*)\)", open(header).read()))
names = sorted(names)
names = [n for n in names if not n.startswith("sub_")]
with open(sys.argv[-1], "w", newline="\n") as out:
    out.write("// Generated by tools/genstubs.py. Weak fallbacks for every import the\n")
    out.write("// title calls; each logs its first call and returns 0.\n")
    out.write('#include "kernel/imports.h"\n\n')
    for n in names:
        out.write(f"__attribute__((weak)) PPC_FUNC(__imp__{n})\n{{\n")
        out.write(f'    LOG_ONCE("unimplemented import {n} (lr %08llX)", ctx.lr);\n')
        out.write("    Return(ctx, 0);\n}\n\n")
print(len(names), "stubs")
