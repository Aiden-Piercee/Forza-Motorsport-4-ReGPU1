#!/usr/bin/env python3
"""Write the table of recompiled images (src/recomp_modules.h) from XenonRecomp configs.

  genmodules.py <out.cpp> <config.toml>...

The first config is the title's executable. Each config's out_directory_path must
already hold XenonRecomp's output: the image and code ranges come from its
ppc_config.h, the mapping table's name from symbol_prefix.
"""
import os
import re
import sys
import tomllib


def read_module(config_path):
    with open(config_path, "rb") as f:
        main = tomllib.load(f)["main"]
    root = os.path.dirname(os.path.abspath(config_path))
    out_dir = os.path.normpath(os.path.join(root, main["out_directory_path"]))
    text = open(os.path.join(out_dir, "ppc_config.h")).read()
    values = {}
    for key in ("PPC_IMAGE_BASE", "PPC_IMAGE_SIZE", "PPC_CODE_BASE", "PPC_CODE_SIZE"):
        m = re.search(rf"#define {key} 0x([0-9A-F]+)ull", text)
        if not m:
            sys.exit(f"{out_dir}/ppc_config.h: no {key}")
        values[key] = int(m.group(1), 16)
    return dict(
        guest_path="game:\\\\" + os.path.basename(main["file_path"]),
        prefix=main.get("symbol_prefix", ""),
        **values,
    )


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    modules = [read_module(p) for p in sys.argv[2:]]
    lines = [
        "// Generated by tools/genmodules.py from the XenonRecomp configs.",
        '#include "recomp_modules.h"',
        '#include "ppc_context.h"',
        "",
    ]
    lines += [f"extern PPCFuncMapping {m['prefix']}PPCFuncMappings[];" for m in modules]
    lines += ["", "const RecompiledModule g_recompiledModules[] = {"]
    for m in modules:
        lines.append(
            f'    {{ "{m["guest_path"]}", 0x{m["PPC_IMAGE_BASE"]:08X}, 0x{m["PPC_IMAGE_SIZE"]:08X}, '
            f'0x{m["PPC_CODE_BASE"]:08X}, 0x{m["PPC_CODE_SIZE"]:08X}, {m["prefix"]}PPCFuncMappings }},'
        )
    lines += ["};", f"const size_t g_recompiledModuleCount = {len(modules)};", ""]
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
    new = "\n".join(lines)
    if not os.path.exists(sys.argv[1]) or open(sys.argv[1]).read() != new:
        with open(sys.argv[1], "w", newline="\n") as f:
            f.write(new)
    print(f"{len(modules)} recompiled images")


if __name__ == "__main__":
    main()
